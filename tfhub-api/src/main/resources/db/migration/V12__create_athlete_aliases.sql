CREATE FUNCTION normalize_athlete_alias(input TEXT)
RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE
AS $$
    SELECT normalize(coalesce(string_agg(
        CASE WHEN char_length(token) = 2
                  AND right(token, 1) = '.'
                  AND left(token, 1) ~ '^[[:alpha:]]$'
             THEN left(token, 1) ELSE token END,
        ' ' ORDER BY position), ''), NFC)
    FROM regexp_split_to_table(
        trim(regexp_replace(
            translate(lower(normalize(input, NFC)),
                U&'\0009\000A\000B\000C\000D\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000',
                repeat(' ', 25)),
            ' +', ' ', 'g')), ' ') WITH ORDINALITY AS words(token, position)
    WHERE token <> ''
$$;

CREATE TABLE athlete_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id BIGINT NOT NULL REFERENCES athletes(id) ON DELETE RESTRICT,
    alias TEXT NOT NULL,
    normalized_alias TEXT GENERATED ALWAYS AS (normalize_athlete_alias(alias)) STORED,
    training_group_id BIGINT REFERENCES training_groups(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL,
    CONSTRAINT ck_athlete_alias_length CHECK (char_length(alias) BETWEEN 1 AND 255),
    CONSTRAINT ck_athlete_alias_normalized CHECK (
        char_length(normalized_alias) BETWEEN 1 AND 255),
    CONSTRAINT uq_athlete_alias_athlete UNIQUE (athlete_id, normalized_alias)
);

CREATE UNIQUE INDEX uq_athlete_alias_active_group
    ON athlete_aliases (training_group_id, normalized_alias)
    WHERE active AND training_group_id IS NOT NULL;

CREATE FUNCTION set_athlete_alias_scope()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    SELECT training_group_id, active INTO STRICT NEW.training_group_id, NEW.active
    FROM athletes WHERE id = NEW.athlete_id FOR UPDATE;
    RETURN NEW;
END
$$;

CREATE TRIGGER athlete_alias_scope_before_write
    BEFORE INSERT OR UPDATE ON athlete_aliases
    FOR EACH ROW EXECUTE FUNCTION set_athlete_alias_scope();

CREATE FUNCTION propagate_athlete_alias_scope()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.active IS DISTINCT FROM OLD.active
            OR NEW.training_group_id IS DISTINCT FROM OLD.training_group_id THEN
        UPDATE athlete_aliases SET active = NEW.active, training_group_id = NEW.training_group_id
        WHERE athlete_id = NEW.id;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER athlete_alias_scope_after_athlete_update
    AFTER UPDATE OF active, training_group_id ON athletes
    FOR EACH ROW EXECUTE FUNCTION propagate_athlete_alias_scope();
