
CREATE TABLE athletes (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          first_name VARCHAR(100) NOT NULL,
                          last_name VARCHAR(100) NOT NULL,
                          birth_year INTEGER NOT NULL,
                          gender VARCHAR(20) NOT NULL,
                          active BOOLEAN NOT NULL DEFAULT TRUE,

                          CONSTRAINT uq_athletes_name_birth_year
                              UNIQUE (first_name, last_name, birth_year)
);

CREATE TABLE tests (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(150) NOT NULL,
                       unit VARCHAR(10) NOT NULL,
                       category VARCHAR(30) NOT NULL,
                       higher_is_better BOOLEAN NOT NULL,
                       active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE test_results (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              athlete_id BIGINT NOT NULL,
                              test_id BIGINT NOT NULL,
                              result_date DATE NOT NULL,
                              value NUMERIC(12, 3) NOT NULL,
                              type VARCHAR(30) NOT NULL,

                              CONSTRAINT fk_test_results_athlete
                                  FOREIGN KEY (athlete_id)
                                      REFERENCES athletes (id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT fk_test_results_test
                                  FOREIGN KEY (test_id)
                                      REFERENCES tests (id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT chk_test_results_value_positive
                                  CHECK (value > 0)
);

CREATE INDEX idx_test_results_athlete_id
    ON test_results (athlete_id);

CREATE INDEX idx_test_results_test_id
    ON test_results (test_id);

CREATE INDEX idx_test_results_date
    ON test_results (result_date);
