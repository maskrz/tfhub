ALTER TABLE training_imports
    ADD COLUMN training_type VARCHAR(32) NOT NULL DEFAULT 'TEMPO',
    ADD CONSTRAINT ck_training_imports_training_type
        CHECK (training_type IN ('TEMPO', 'FREE_TEXT'));

CREATE TABLE training_import_draft_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    recognition_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_training_import_draft_sections_sequence_positive
        CHECK (sequence_number > 0),
    CONSTRAINT ck_training_import_draft_sections_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT uq_training_import_draft_sections_sequence
        UNIQUE (draft_id, sequence_number),
    CONSTRAINT fk_training_import_draft_sections_draft
        FOREIGN KEY (draft_id) REFERENCES training_import_drafts (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_import_draft_sections_draft_sequence
    ON training_import_draft_sections (draft_id, sequence_number);
