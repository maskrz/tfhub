CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'COACH', 'ATHLETE')),
    CONSTRAINT chk_users_username_nonblank CHECK (length(trim(username)) > 0)
);

CREATE UNIQUE INDEX uq_users_normalized_username
    ON users (lower(trim(username)));

CREATE TABLE training_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    coach_name VARCHAR(150),
    CONSTRAINT chk_training_groups_name_nonblank CHECK (length(trim(name)) > 0)
);

CREATE TABLE user_training_group (
    user_id BIGINT NOT NULL,
    training_group_id BIGINT NOT NULL,
    CONSTRAINT pk_user_training_group PRIMARY KEY (user_id, training_group_id),
    CONSTRAINT fk_user_training_group_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_training_group_group
        FOREIGN KEY (training_group_id) REFERENCES training_groups (id) ON DELETE RESTRICT
);

CREATE INDEX idx_user_training_group_group
    ON user_training_group (training_group_id, user_id);

CREATE TABLE user_athlete_access (
    user_id BIGINT NOT NULL,
    athlete_id BIGINT NOT NULL,
    CONSTRAINT pk_user_athlete_access PRIMARY KEY (user_id, athlete_id),
    CONSTRAINT fk_user_athlete_access_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_athlete_access_athlete
        FOREIGN KEY (athlete_id) REFERENCES athletes (id) ON DELETE RESTRICT
);

CREATE INDEX idx_user_athlete_access_athlete
    ON user_athlete_access (athlete_id, user_id);

ALTER TABLE athletes
    ADD COLUMN training_group_id BIGINT,
    ADD CONSTRAINT fk_athletes_training_group
        FOREIGN KEY (training_group_id) REFERENCES training_groups (id) ON DELETE RESTRICT;

CREATE INDEX idx_athletes_training_group_active
    ON athletes (training_group_id, active);
