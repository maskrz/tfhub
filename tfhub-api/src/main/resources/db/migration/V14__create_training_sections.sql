CREATE TABLE training_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_session_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    sequence_number INTEGER NOT NULL,
    CONSTRAINT ck_training_sections_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT ck_training_sections_content_not_blank CHECK (LENGTH(TRIM(content)) > 0),
    CONSTRAINT ck_training_sections_sequence_positive CHECK (sequence_number > 0),
    CONSTRAINT uq_training_sections_session_sequence
        UNIQUE (training_session_id, sequence_number) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_training_sections_session
        FOREIGN KEY (training_session_id) REFERENCES training_sessions (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_sections_session_sequence
    ON training_sections (training_session_id, sequence_number);
