CREATE TABLE training_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_group_id BIGINT NOT NULL,
    initiated_by_user_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    possible_duplicate BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_training_imports_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'REVIEW_REQUIRED', 'FAILED', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT fk_training_imports_group
        FOREIGN KEY (training_group_id) REFERENCES training_groups (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_imports_initiated_by
        FOREIGN KEY (initiated_by_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_imports_group_status_created_at
    ON training_imports (training_group_id, status, created_at DESC, id);
CREATE INDEX idx_training_imports_initiated_by_user
    ON training_imports (initiated_by_user_id);

CREATE TABLE training_import_source_images (
    import_id BIGINT PRIMARY KEY,
    storage_key VARCHAR(255) NOT NULL,
    media_type VARCHAR(50) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    byte_size BIGINT NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    CONSTRAINT uq_training_import_source_images_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_training_import_source_images_media_type
        CHECK (media_type = 'image/jpeg'),
    CONSTRAINT ck_training_import_source_images_byte_size
        CHECK (byte_size > 0),
    CONSTRAINT ck_training_import_source_images_dimensions
        CHECK (width > 0 AND height > 0),
    CONSTRAINT ck_training_import_source_images_sha256
        CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT fk_training_import_source_images_import
        FOREIGN KEY (import_id) REFERENCES training_imports (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_import_source_images_sha256
    ON training_import_source_images (sha256);
