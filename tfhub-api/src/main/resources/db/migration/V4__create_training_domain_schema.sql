CREATE TABLE training_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    training_date DATE NOT NULL,
    training_group_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_training_sessions_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT fk_training_sessions_group
        FOREIGN KEY (training_group_id) REFERENCES training_groups (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_sessions_group_active_date
    ON training_sessions (training_group_id, active, training_date DESC, id);

CREATE TABLE training_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_session_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    sequence_number INTEGER NOT NULL,
    CONSTRAINT ck_training_definitions_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_training_definitions_sequence_positive CHECK (sequence_number > 0),
    CONSTRAINT uq_training_definitions_session_sequence UNIQUE (training_session_id, sequence_number),
    CONSTRAINT uq_training_definitions_id_session UNIQUE (id, training_session_id),
    CONSTRAINT fk_training_definitions_session
        FOREIGN KEY (training_session_id) REFERENCES training_sessions (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE training_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_definition_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    distance_m INTEGER NOT NULL,
    rest_after_seconds INTEGER,
    CONSTRAINT ck_training_segments_sequence_positive CHECK (sequence_number > 0),
    CONSTRAINT ck_training_segments_distance_positive CHECK (distance_m > 0),
    CONSTRAINT ck_training_segments_rest_non_negative
        CHECK (rest_after_seconds IS NULL OR rest_after_seconds >= 0),
    CONSTRAINT uq_training_segments_definition_sequence UNIQUE (training_definition_id, sequence_number),
    CONSTRAINT uq_training_segments_id_definition UNIQUE (id, training_definition_id),
    CONSTRAINT fk_training_segments_definition
        FOREIGN KEY (training_definition_id) REFERENCES training_definitions (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE training_athlete_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_session_id BIGINT NOT NULL,
    training_definition_id BIGINT NOT NULL,
    athlete_id BIGINT NOT NULL,
    CONSTRAINT uq_training_participations_session_athlete UNIQUE (training_session_id, athlete_id),
    CONSTRAINT uq_training_participations_id_definition UNIQUE (id, training_definition_id),
    CONSTRAINT fk_training_participations_session
        FOREIGN KEY (training_session_id) REFERENCES training_sessions (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_participations_definition_session
        FOREIGN KEY (training_definition_id, training_session_id)
        REFERENCES training_definitions (id, training_session_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_participations_athlete
        FOREIGN KEY (athlete_id) REFERENCES athletes (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_participations_definition
    ON training_athlete_participations (training_definition_id);
CREATE INDEX idx_training_participations_athlete
    ON training_athlete_participations (athlete_id);

CREATE TABLE training_segment_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id BIGINT NOT NULL,
    training_segment_id BIGINT NOT NULL,
    training_definition_id BIGINT NOT NULL,
    status VARCHAR(40) NOT NULL,
    measured_result NUMERIC(12, 3),
    uses_spikes BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_training_executions_status
        CHECK (status IN ('PENDING', 'RECORDED', 'COMPLETED_WITHOUT_RESULT', 'NOT_COMPLETED')),
    CONSTRAINT ck_training_executions_result_non_negative
        CHECK (measured_result IS NULL OR measured_result >= 0),
    CONSTRAINT ck_training_executions_result_matches_status
        CHECK ((status = 'RECORDED' AND measured_result IS NOT NULL)
            OR (status <> 'RECORDED' AND measured_result IS NULL)),
    CONSTRAINT uq_training_executions_participation_segment
        UNIQUE (participation_id, training_segment_id),
    CONSTRAINT fk_training_executions_participation_definition
        FOREIGN KEY (participation_id, training_definition_id)
        REFERENCES training_athlete_participations (id, training_definition_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_executions_segment_definition
        FOREIGN KEY (training_segment_id, training_definition_id)
        REFERENCES training_segments (id, training_definition_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_executions_segment
    ON training_segment_executions (training_segment_id);
CREATE INDEX idx_training_executions_definition
    ON training_segment_executions (training_definition_id);
