ALTER TABLE athletes
    ADD COLUMN pzla_id VARCHAR(20),
    ADD CONSTRAINT ck_athletes_pzla_id_digits
        CHECK (pzla_id IS NULL OR pzla_id ~ '^[0-9]+$');

CREATE UNIQUE INDEX uq_athletes_pzla_id
    ON athletes (pzla_id)
    WHERE pzla_id IS NOT NULL;

CREATE TABLE competition_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uq_competition_events_normalized_name
    ON competition_events (LOWER(TRIM(name)));

CREATE TABLE competition_sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id BIGINT NOT NULL,
    sync_mode VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    error_code VARCHAR(60),
    error_message VARCHAR(500),

    CONSTRAINT fk_competition_sync_runs_athlete
        FOREIGN KEY (athlete_id) REFERENCES athletes (id) ON DELETE RESTRICT,
    CONSTRAINT ck_competition_sync_runs_mode
        CHECK (sync_mode IN ('CURRENT_SEASON', 'FULL_HISTORY')),
    CONSTRAINT ck_competition_sync_runs_status
        CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE INDEX idx_competition_sync_runs_athlete_requested
    ON competition_sync_runs (athlete_id, requested_at DESC, id DESC);

CREATE UNIQUE INDEX uq_competition_sync_runs_active_athlete
    ON competition_sync_runs (athlete_id)
    WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE competition_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    result_date DATE NOT NULL,
    original_mark VARCHAR(50) NOT NULL,
    numeric_value NUMERIC(12, 3),
    unit VARCHAR(10) NOT NULL,
    wind NUMERIC(6, 2),
    season INTEGER,
    season_type VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    competition_name VARCHAR(250),
    location VARCHAR(250),
    result_round VARCHAR(100),
    source VARCHAR(20) NOT NULL,
    source_record_key VARCHAR(255),
    source_fingerprint VARCHAR(64),

    CONSTRAINT fk_competition_results_athlete
        FOREIGN KEY (athlete_id) REFERENCES athletes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_competition_results_event
        FOREIGN KEY (event_id) REFERENCES competition_events (id) ON DELETE RESTRICT,
    CONSTRAINT ck_competition_results_season_type
        CHECK (season_type IN ('INDOOR', 'OUTDOOR', 'UNKNOWN')),
    CONSTRAINT ck_competition_results_source
        CHECK (source IN ('PZLA', 'MANUAL')),
    CONSTRAINT ck_competition_results_source_fields
        CHECK (
            (source = 'PZLA' AND source_fingerprint IS NOT NULL)
            OR (source = 'MANUAL' AND source_record_key IS NULL AND source_fingerprint IS NULL)
        )
);

CREATE INDEX idx_competition_results_athlete_date
    ON competition_results (athlete_id, result_date DESC, id DESC);

CREATE INDEX idx_competition_results_event
    ON competition_results (event_id);

CREATE UNIQUE INDEX uq_competition_results_source_record
    ON competition_results (athlete_id, source_record_key)
    WHERE source = 'PZLA' AND source_record_key IS NOT NULL;

CREATE UNIQUE INDEX uq_competition_results_source_fingerprint
    ON competition_results (athlete_id, source_fingerprint)
    WHERE source = 'PZLA';
