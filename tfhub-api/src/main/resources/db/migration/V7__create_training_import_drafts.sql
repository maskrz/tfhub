CREATE TABLE training_import_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id BIGINT NOT NULL,
    attempt_number INTEGER NOT NULL,
    requested_by_user_id BIGINT,
    model_name VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    raw_model_response TEXT,
    failure_code VARCHAR(100),
    failure_message TEXT,
    CONSTRAINT ck_training_import_attempts_number_positive
        CHECK (attempt_number > 0),
    CONSTRAINT ck_training_import_attempts_status
        CHECK (status IN ('PROCESSING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_training_import_attempts_finished_at
        CHECK ((status = 'PROCESSING' AND finished_at IS NULL)
            OR (status <> 'PROCESSING' AND finished_at IS NOT NULL)),
    CONSTRAINT uq_training_import_attempts_import_number
        UNIQUE (import_id, attempt_number),
    CONSTRAINT uq_training_import_attempts_id_import
        UNIQUE (id, import_id),
    CONSTRAINT fk_training_import_attempts_import
        FOREIGN KEY (import_id) REFERENCES training_imports (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_import_attempts_requested_by
        FOREIGN KEY (requested_by_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_training_import_attempts_processing
    ON training_import_attempts (import_id)
    WHERE status = 'PROCESSING';

CREATE TABLE training_import_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id BIGINT NOT NULL,
    generated_by_attempt_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    training_date DATE NOT NULL,
    recognition_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_training_import_drafts_import UNIQUE (import_id),
    CONSTRAINT uq_training_import_drafts_id_import UNIQUE (id, import_id),
    CONSTRAINT ck_training_import_drafts_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT fk_training_import_drafts_import
        FOREIGN KEY (import_id) REFERENCES training_imports (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_import_drafts_generated_attempt
        FOREIGN KEY (generated_by_attempt_id, import_id)
        REFERENCES training_import_attempts (id, import_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE training_import_draft_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    sequence_number INTEGER NOT NULL,
    CONSTRAINT ck_training_import_draft_definitions_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_training_import_draft_definitions_sequence_positive
        CHECK (sequence_number > 0),
    CONSTRAINT uq_training_import_draft_definitions_sequence
        UNIQUE (draft_id, sequence_number),
    CONSTRAINT uq_training_import_draft_definitions_id_draft
        UNIQUE (id, draft_id),
    CONSTRAINT fk_training_import_draft_definitions_draft
        FOREIGN KEY (draft_id) REFERENCES training_import_drafts (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_import_draft_definitions_draft
    ON training_import_draft_definitions (draft_id);

CREATE TABLE training_import_draft_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    definition_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    distance_m INTEGER NOT NULL,
    rest_after_seconds INTEGER,
    recognition_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_training_import_draft_segments_sequence_positive
        CHECK (sequence_number > 0),
    CONSTRAINT ck_training_import_draft_segments_distance_positive
        CHECK (distance_m > 0),
    CONSTRAINT ck_training_import_draft_segments_rest_non_negative
        CHECK (rest_after_seconds IS NULL OR rest_after_seconds >= 0),
    CONSTRAINT uq_training_import_draft_segments_definition_sequence
        UNIQUE (definition_id, sequence_number),
    CONSTRAINT uq_training_import_draft_segments_id_draft_definition
        UNIQUE (id, draft_id, definition_id),
    CONSTRAINT fk_training_import_draft_segments_definition_draft
        FOREIGN KEY (definition_id, draft_id)
        REFERENCES training_import_draft_definitions (id, draft_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_import_draft_segments_draft_definition
    ON training_import_draft_segments (draft_id, definition_id, sequence_number);

CREATE TABLE training_import_draft_athlete_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    definition_id BIGINT NOT NULL,
    athlete_id BIGINT,
    recognized_name TEXT NOT NULL,
    match_status VARCHAR(16) NOT NULL,
    recognition_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_training_import_draft_athlete_rows_match_status
        CHECK (match_status IN ('UNRESOLVED', 'MATCHED', 'SKIPPED')),
    CONSTRAINT ck_training_import_draft_athlete_rows_match
        CHECK ((match_status = 'MATCHED' AND athlete_id IS NOT NULL)
            OR (match_status IN ('UNRESOLVED', 'SKIPPED') AND athlete_id IS NULL)),
    CONSTRAINT uq_training_import_draft_athlete_rows_id_draft_definition
        UNIQUE (id, draft_id, definition_id),
    CONSTRAINT fk_training_import_draft_athlete_rows_definition_draft
        FOREIGN KEY (definition_id, draft_id)
        REFERENCES training_import_draft_definitions (id, draft_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_import_draft_athlete_rows_athlete
        FOREIGN KEY (athlete_id) REFERENCES athletes (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_training_import_draft_athlete_rows_matched_athlete
    ON training_import_draft_athlete_rows (draft_id, athlete_id)
    WHERE match_status = 'MATCHED' AND athlete_id IS NOT NULL;

CREATE INDEX idx_training_import_draft_athlete_rows_definition
    ON training_import_draft_athlete_rows (definition_id);

CREATE TABLE training_import_draft_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    definition_id BIGINT NOT NULL,
    athlete_row_id BIGINT NOT NULL,
    segment_id BIGINT NOT NULL,
    status VARCHAR(40) NOT NULL,
    measured_result NUMERIC(12, 3),
    uses_spikes BOOLEAN,
    recognized_text TEXT,
    recognition_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_training_import_draft_executions_status
        CHECK (status IN ('PENDING', 'RECORDED', 'COMPLETED_WITHOUT_RESULT', 'NOT_COMPLETED')),
    CONSTRAINT ck_training_import_draft_executions_result_non_negative
        CHECK (measured_result IS NULL OR measured_result >= 0),
    CONSTRAINT ck_training_import_draft_executions_result_matches_status
        CHECK ((status = 'RECORDED' AND measured_result IS NOT NULL)
            OR (status <> 'RECORDED' AND measured_result IS NULL)),
    CONSTRAINT uq_training_import_draft_executions_row_segment
        UNIQUE (athlete_row_id, segment_id),
    CONSTRAINT fk_training_import_draft_executions_athlete_row
        FOREIGN KEY (athlete_row_id, draft_id, definition_id)
        REFERENCES training_import_draft_athlete_rows (id, draft_id, definition_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_training_import_draft_executions_segment
        FOREIGN KEY (segment_id, draft_id, definition_id)
        REFERENCES training_import_draft_segments (id, draft_id, definition_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_training_import_draft_executions_draft_definition
    ON training_import_draft_executions (draft_id, definition_id);
CREATE INDEX idx_training_import_draft_executions_segment
    ON training_import_draft_executions (segment_id);
